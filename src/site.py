"""Static index page that lists the combined and per-category feeds."""

from __future__ import annotations

import html
import os
from pathlib import Path
from typing import Mapping, Sequence

from .categories import Category, category_feed_path
from .textutil import sanitize_xml

PAGE_TEMPLATE = """<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>{title}</title>
    <link rel="alternate" type="application/rss+xml" title="{title}" href="feed.xml" />
    <style>
      :root {{ color-scheme: light dark; }}
      body {{
        font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
        max-width: 46rem;
        margin: 4rem auto;
        padding: 0 1.25rem;
        line-height: 1.6;
      }}
      table {{ width: 100%; border-collapse: collapse; margin: 1.5rem 0; }}
      th, td {{ text-align: left; padding: 0.5rem 0.4rem; border-bottom: 1px solid rgba(127, 127, 127, 0.3); }}
      th {{ font-size: 0.85rem; text-transform: uppercase; letter-spacing: 0.04em; opacity: 0.7; }}
      td.num {{ text-align: right; white-space: nowrap; }}
      code {{ padding: 0.15rem 0.35rem; border-radius: 0.25rem; background: rgba(127, 127, 127, 0.2); }}
      .muted {{ opacity: 0.7; font-size: 0.9rem; }}
    </style>
  </head>
  <body>
    <h1>{title}</h1>
    <p>{description}</p>
    <p>
      Every article is fetched from its source feed, extracted with trafilatura, ranked by an LLM
      against a reader-interest profile, then condensed into a short, faithful version. Each item
      links back to the original article, which remains the only authoritative source.
    </p>
    <p><strong>All categories:</strong> <a href="feed.xml"><code>feed.xml</code></a></p>
    <table>
      <thead>
        <tr><th>Category</th><th class="num">Sources</th><th class="num">Items</th><th>Feed</th></tr>
      </thead>
      <tbody>
{rows}
      </tbody>
    </table>
    <p class="muted">
      Feed descriptions are labelled <strong>AI 精简版</strong>. Generated by
      <strong>FeedOverview</strong> — GitHub Actions + GitHub Pages.
    </p>
  </body>
</html>
"""


def _esc(value: object) -> str:
    return html.escape(sanitize_xml(str(value or "")), quote=True)


def write_index(
    categories: Sequence[Category],
    cfg: dict,
    item_counts: Mapping[str, int] | None = None,
    source_counts: Mapping[str, int] | None = None,
    path: str | os.PathLike[str] | None = None,
) -> Path:
    """Render ``index.html`` next to the combined feed so every category is discoverable."""
    item_counts = item_counts or {}
    source_counts = source_counts or {}
    out = Path(path or Path(cfg.get("output_path") or "docs/feed.xml").parent / "index.html")
    out.parent.mkdir(parents=True, exist_ok=True)

    rows: list[str] = []
    for category in categories:
        feed_name = category_feed_path(cfg.get("output_path") or "docs/feed.xml", category.key).name
        rows.append(
            "        <tr>"
            f'<td><a href="feeds/{_esc(feed_name)}">{_esc(category.label)}</a>'
            f'<br /><span class="muted">{_esc(category.key)}</span></td>'
            f'<td class="num">{int(source_counts.get(category.key, 0))}</td>'
            f'<td class="num">{int(item_counts.get(category.key, 0))}</td>'
            f'<td><a href="feeds/{_esc(feed_name)}"><code>{_esc(feed_name)}</code></a></td>'
            "</tr>"
        )

    page = PAGE_TEMPLATE.format(
        title=_esc(cfg.get("feed_title") or "Curated Feed"),
        description=_esc(cfg.get("feed_description") or ""),
        rows="\n".join(rows),
    )
    tmp = out.with_name(out.name + ".tmp")
    tmp.write_text(page, encoding="utf-8")
    os.replace(tmp, out)
    return out
